#!/usr/bin/env python3
"""Build the Phosphor icon-font subset that the site actually ships.

The full Phosphor 2.1.2 regular font is 147 KB (1530 icons) and was
preloaded on every page, while the site uses ~140 icons. This writes
``static/vendor/phosphor-icons-web/2.1.2/subset/{regular,fill}/`` with only
the icons named anywhere in the tracked sources (``ph-<name>``).

Re-run after adding an icon; ``games/tests/test_frontend_assets.py`` fails
when a referenced icon is missing from the subset.

Needs fonttools and brotli (build-time only):
    python3 -m venv /tmp/fontvenv && /tmp/fontvenv/bin/pip install fonttools brotli
    /tmp/fontvenv/bin/python scripts/build_phosphor_subset.py
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / 'static/vendor/phosphor-icons-web/2.1.2'
OUT = VENDOR / 'subset'
VARIANTS = (
    # (dir, css selector prefix, font file)
    ('regular', '.ph', 'Phosphor.woff2'),
    ('fill', '.ph-fill', 'Phosphor-Fill.woff2'),
)
# The icon picker is a design tool that shows the whole set from the full font.
SCAN_EXCLUDE = ('static/vendor/', 'static/design-icon-picker.html', 'var/')
SCAN_SUFFIXES = ('.html', '.js', '.py', '.css', '.txt', '.md', '.json')
NAME_RE = re.compile(r'\bph-([a-z0-9]+(?:-[a-z0-9]+)*)')
RULE_RE = re.compile(r'(?P<prefix>\.ph(?:-fill)?)\.ph-(?P<name>[a-z0-9-]+):before \{\s*content: "\\(?P<code>[0-9a-f]+)";\s*\}')


def tracked_sources():
    files = subprocess.run(
        ['git', 'ls-files'], cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout.split()
    for rel in files:
        if rel.startswith(SCAN_EXCLUDE) or '/releases/' in rel or not rel.endswith(SCAN_SUFFIXES):
            continue
        if rel.startswith('static/vendor/phosphor'):
            continue
        yield ROOT / rel


def used_icon_names(defined: set[str]) -> set[str]:
    names = set()
    for path in tracked_sources():
        try:
            text = path.read_text(encoding='utf-8')
        except (UnicodeDecodeError, FileNotFoundError):
            continue
        names.update(match for match in NAME_RE.findall(text) if match in defined)
    return names


def icon_rules(css: str) -> dict[str, str]:
    return {m.group('name'): m.group('code') for m in RULE_RE.finditer(css)}


def build_variant(directory: str, prefix: str, font_file: str, names: set[str]) -> tuple[int, int]:
    source_css = (VENDOR / directory / 'style.css').read_text(encoding='utf-8')
    rules = icon_rules(source_css)
    wanted = sorted(name for name in names if name in rules)
    codes = ','.join('U+{}'.format(rules[name].upper()) for name in wanted)

    out_dir = OUT / directory
    out_dir.mkdir(parents=True, exist_ok=True)
    out_font = out_dir / font_file
    from fontTools import subset

    subset.main([
        str(VENDOR / directory / font_file),
        '--unicodes={}'.format(codes),
        '--flavor=woff2',
        '--layout-features=',
        '--no-hinting',
        '--desubroutinize',
        '--output-file={}'.format(out_font),
    ])

    header = source_css[:source_css.index('{}.ph-'.format(prefix))]
    # One woff2 source; no browser that runs this site lacks woff2.
    header = re.sub(
        r'src:\s*url\("\./([^"]+\.woff2)"\) format\("woff2"\),\s*url\("[^"]+"\) format\("woff"\);',
        r'src: url("./\1") format("woff2");',
        header,
    )
    body = ''.join(
        '{}.ph-{}:before {{\n  content: "\\{}";\n}}\n'.format(prefix, name, rules[name])
        for name in wanted
    )
    (out_dir / 'style.css').write_text(
        '/* Generated by scripts/build_phosphor_subset.py; do not edit. */\n' + header + body,
        encoding='utf-8',
    )
    return len(wanted), out_font.stat().st_size


def main() -> int:
    regular_rules = icon_rules((VENDOR / 'regular' / 'style.css').read_text(encoding='utf-8'))
    names = used_icon_names(set(regular_rules))
    for directory, prefix, font_file in VARIANTS:
        count, size = build_variant(directory, prefix, font_file, names)
        print('{}: {} icons, {} bytes'.format(directory, count, size))
    return 0


if __name__ == '__main__':
    sys.exit(main())
