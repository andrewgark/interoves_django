"""Client specs give the verdicts of the server checkers they describe.

contracts/client_spec.json pins specs and verdicts for the browser twin.
Regenerate it after an intended change with:
    INTEROVES_UPDATE_CONTRACTS=1 ./run_tests.sh games.tests.test_client_spec
"""
import json
import os
from pathlib import Path
from types import SimpleNamespace

from django.conf import settings
from django.test import SimpleTestCase, TestCase

from games.gameplay.attempts import client_spec_for_task
from games.models import CheckerType, Task, TaskGroup
from games.puzzles.core.check_runtime import CheckerFactory
from games.puzzles.core.client_spec import verify, verify_word
from games.puzzles.raddle.engine import word_matches
from games.puzzles.raddle.submission import RaddleChecker

CONTRACT = Path(settings.BASE_DIR) / 'contracts' / 'client_spec.json'
TASK = SimpleNamespace(id=7, attempt_revision='3f1c')

ANSWER_CASES = [
    ('equals', 'Ёжик в тумане', [
        'ёжик в тумане', '  ЕЖИК В ТУМАНЕ ', 'ежик в тумане!', 'ежик  в тумане', 'ежик', '',
    ]),
    ('equals_with_possible_spaces', 'Нью-Йорк\nНью Йорк\nNYC', [
        'нью-йорк', 'НЬЮЙОРК', 'нью  йорк', 'nyc', 'n y c', 'н.ь.ю.й.о.р.к', 'лондон', '',
    ]),
    ('several_answers', '100 москва\n50 мск\n0 столица', [
        'Москва', 'мск', 'столица', ' москва ', 'питер', '',
    ]),
    ('any_answer', '', ['что угодно', '']),
]

LADDER = {
    'task_type': 'raddle',
    'answer': '',
    'checker_data': json.dumps({
        'lengths': [3, 4, '3-4', 3],
        'hints': ['h0', 'h1', 'h2'],
        'words': ['КОТ', 'ЁЛКА|ЕЛКА', 'ПОЛ-ЛИТ', 'Dog'],
    }, ensure_ascii=False),
}
LADDER_WORDS = [
    (0, 'кот'), (0, 'КОТ!'), (0, 'кит'), (1, 'елка'), (1, 'Ёлка'), (1, 'ёлки'),
    (2, 'пол литр'), (2, 'поллит'), (2, 'пол-лит'), (3, 'DOG'), (3, 'дог'), (4, 'кот'), (-1, 'кот'),
]


def answer_checker(checker_id, data):
    return CheckerFactory().create_checker(SimpleNamespace(id=checker_id), data)


def build_contract():
    answers = []
    for checker_id, data, texts in ANSWER_CASES:
        checker = answer_checker(checker_id, data)
        answers.append({
            'checker': checker_id,
            'spec': checker.client_spec(TASK),
            'cases': [{'text': text, 'status': checker.check(text, None).status} for text in texts],
        })
    ladder_task = SimpleNamespace(id=TASK.id, attempt_revision=TASK.attempt_revision, **LADDER)
    parsed_accept = json.loads(LADDER['checker_data'])['words']
    ladder = {
        'spec': RaddleChecker('').client_spec(ladder_task),
        'cases': [
            {
                'word_index': index,
                'word': word,
                'accepted': 0 <= index < len(parsed_accept) and word_matches(
                    word, parsed_accept[index].split('|'),
                ),
            }
            for index, word in LADDER_WORDS
        ],
    }
    return {
        '_comment': 'Generated by games/tests/test_client_spec.py from the server checkers.',
        'answers': answers,
        'ladder': ladder,
    }


class ClientSpecParityTests(SimpleTestCase):
    def test_spec_verdict_matches_the_checker(self):
        for checker_id, data, texts in ANSWER_CASES:
            checker = answer_checker(checker_id, data)
            spec = checker.client_spec(TASK)
            for text in texts:
                with self.subTest(checker=checker_id, text=text):
                    self.assertEqual(verify(spec, text), checker.check(text, None).status)

    def test_ladder_spec_matches_word_matches(self):
        contract = build_contract()['ladder']
        for case in contract['cases']:
            with self.subTest(case=case):
                self.assertEqual(
                    verify_word(contract['spec'], case['word_index'], case['word']), case['accepted'],
                )

    def test_spec_does_not_contain_the_answers(self):
        contract = build_contract()
        specs = [entry['spec'] for entry in contract['answers']] + [contract['ladder']['spec']]
        dumped = json.dumps(specs, ensure_ascii=False).lower()
        for word in ('ежик', 'москва', 'нью', 'кот', 'елка', 'dog'):
            self.assertNotIn(word, dumped)

    def test_salt_depends_on_the_task_revision(self):
        checker = answer_checker('equals', 'ответ')
        other = SimpleNamespace(id=TASK.id, attempt_revision='other')
        self.assertNotEqual(checker.client_spec(TASK)['accept'], checker.client_spec(other)['accept'])

    def test_checkers_without_a_spec_stay_on_the_server(self):
        self.assertIsNone(answer_checker('regexp', 'отв.т').client_spec(TASK))
        self.assertIsNone(answer_checker('norm_matcher', 'ответ').client_spec(TASK))

    def test_contract_file_is_up_to_date(self):
        contract = build_contract()
        if os.environ.get('INTEROVES_UPDATE_CONTRACTS') == '1':
            with CONTRACT.open('w', encoding='utf-8') as f:
                json.dump(contract, f, ensure_ascii=False, indent=1)
                f.write('\n')
        with CONTRACT.open(encoding='utf-8') as f:
            self.assertEqual(json.load(f), contract, 'regenerate: see the module docstring')


class ClientSpecForTaskTests(TestCase):
    def test_equals_task_without_checker_data_uses_the_answer(self):
        task = Task.objects.create(
            task_group=TaskGroup.objects.create(label='client_spec_tg'),
            number='1',
            task_type='default',
            checker=CheckerType.objects.get_or_create(pk='equals')[0],
            checker_data='',
            answer='Ответ',
        )
        spec = client_spec_for_task(task)
        self.assertEqual(verify(spec, 'ответ'), 'Ok')
        self.assertEqual(verify(spec, 'другое'), 'Wrong')
        self.assertTrue(spec['salt'].startswith('{}:'.format(task.id)))
