"""Ladder word rules: games/puzzles/raddle/transition.py ↔ static/js/offline_raddle_rules.js.

contracts/raddle_rules.json is generated from the Python rules. Regenerate it
after an intended change with:
    INTEROVES_UPDATE_CONTRACTS=1 ./run_tests.sh games.tests.test_raddle_rules_contract
"""
import json
import os
import random
from pathlib import Path

from django.conf import settings
from django.test import SimpleTestCase

from games.puzzles.raddle.engine import parse_length_mask, playable_word_indices
from games.puzzles.raddle.transition import advance, progress_status, refuse_word, rules_config

CONTRACT = Path(settings.BASE_DIR) / 'contracts' / 'raddle_rules.json'
LADDERS = [
    ['3', '3', '3'],
    ['3', '4', '3-4', '4 2', '3'],
    ['5', 'x', '5', '5', '5', '5', '5'],
    ['2', '2'],
]
WORDS = ['', 'кот', 'КОТЫ', 'пол-лит', 'ab cd', 'дог', 'ёжик!', 'x']


def _parsed(lengths):
    return {
        'n_words': len(lengths),
        'hints': ['h{}'.format(i) for i in range(len(lengths) - 1)],
        'masks': [parse_length_mask(value) for value in lengths],
    }


def build_contract():
    rng = random.Random(20261029)
    ladders = []
    for lengths in LADDERS:
        parsed = _parsed(lengths)
        n = parsed['n_words']
        cases = []
        for _ in range(80):
            state = {
                'solved_indices': sorted(rng.sample(range(n), rng.randint(0, n))),
                'used_hints': sorted(rng.sample(range(n - 1), rng.randint(0, n - 1))),
            }
            playable = sorted(playable_word_indices(state, n))
            length = None
            if playable and rng.random() < 0.6:
                word_index = rng.choice(playable)
                length = rules_config(parsed)['lengths'][word_index]
            else:
                word_index = rng.randint(-1, n)
            word = 'ф' * (length or 3) if length is not None or rng.random() < 0.3 else rng.choice(WORDS)
            case = {
                'state': state,
                'word_index': word_index,
                'word': word,
                'playable': playable,
                'refusal': refuse_word(state, parsed, word_index, word),
            }
            if case['refusal'] is None:
                after = advance(state, parsed, word_index)
                case['advanced'] = {key: after[key] for key in ('solved_indices', 'used_hints')}
                case['status_correct'] = list(progress_status(after, n, word_correct=True))
                case['status_wrong'] = list(progress_status(state, n, word_correct=False))
            cases.append(case)
        ladders.append({'ladder': rules_config(parsed), 'cases': cases})
    return {
        '_comment': 'Generated by games/tests/test_raddle_rules_contract.py from the Python rules.',
        'ladders': ladders,
    }


class RaddleRulesContractTests(SimpleTestCase):
    def test_contract_covers_every_branch(self):
        cases = [case for ladder in build_contract()['ladders'] for case in ladder['cases']]
        refusals = {case['refusal'] for case in cases}
        self.assertIn(None, refusals)
        self.assertEqual(len(refusals), 6, refusals)
        statuses = {tuple(case['status_correct']) for case in cases if 'status_correct' in case}
        self.assertIn(('Ok', 'Ok'), statuses)
        self.assertIn(('Partial', 'Partial'), statuses)

    def test_rules_config_lengths(self):
        self.assertEqual(rules_config(_parsed(['3', '3-4', '4 2', 'x']))['lengths'], [3, 7, 6, None])

    def test_contract_file_is_up_to_date(self):
        contract = build_contract()
        if os.environ.get('INTEROVES_UPDATE_CONTRACTS') == '1':
            with CONTRACT.open('w', encoding='utf-8') as f:
                json.dump(contract, f, ensure_ascii=False, indent=1)
                f.write('\n')
        with CONTRACT.open(encoding='utf-8') as f:
            self.assertEqual(json.load(f), contract, 'regenerate: see the module docstring')
