PRUNE_CONTRACT = Path(settings.BASE_DIR) / 'contracts' / 'word_salad_prune.json'


def _solve_in_order(grid, words, order):
    """Solve ``words`` in ``order`` with the server checker; yield each step."""
    checker_data = serialize_task_data(grid, words)
    state_raw = None
    for index in order:
        active = sorted(load_state(state_raw)['active'])
        path = find_paths(grid, words[index], active=active, limit=1)[0]
        result = WordSaladChecker(checker_data, state_raw).check(json.dumps({'path': path}), None)
        assert result.status in ('Ok', 'Partial'), result
        state_raw = result.state
        state = load_state(state_raw)
        yield {
            'solved_indices': sorted(state['solved_indices']),
            'active_before': active,
            'active_after': sorted(state['active']),
        }


def build_prune_contract():
    """Active cells after every solve of the sample salads in a few orders."""
    cases = []
    for number, salad in sorted(parse_word_salad_csv(SAMPLE_CSV).items()):
        grid = salad['grid']
        words = [normalize_word(word) for word in salad['words']]
        orders = [list(range(len(words))), list(reversed(range(len(words))))]
        rng = random.Random(number)
        for _ in range(3):
            order = list(range(len(words)))
            rng.shuffle(order)
            orders.append(order)
        for order in orders:
            for step in _solve_in_order(grid, words, order):
                cases.append({'grid': grid, 'words': words, **step})
    return {
        '_comment': 'Generated by games/tests/test_word_salad_instant.py from WordSaladChecker.',
        'cases': cases,
    }


class PruneContractTests(SimpleTestCase):
    def test_contract_file_is_up_to_date(self):
        # Regenerate after an intended change:
        #   INTEROVES_UPDATE_CONTRACTS=1 ./run_tests.sh games.tests.test_word_salad_instant
        contract = build_prune_contract()
        self.assertTrue(any(c['active_before'] != c['active_after'] for c in contract['cases']))
        if os.environ.get('INTEROVES_UPDATE_CONTRACTS') == '1':
            with PRUNE_CONTRACT.open('w', encoding='utf-8') as f:
                json.dump(contract, f, ensure_ascii=False, separators=(',', ':'))
                f.write('\n')
        with PRUNE_CONTRACT.open(encoding='utf-8') as f:
            self.assertEqual(json.load(f), contract)


class ClientVerdictOfTests(SimpleTestCase):
    def test_only_a_new_answer_word_is_ok(self):
        def attempt(status, comment=''):
            return SimpleNamespace(status=status, comment=comment)

        self.assertEqual(client_verdict_of(attempt('Partial'), True), 'Ok')
        self.assertEqual(client_verdict_of(attempt('Ok'), True), 'Ok')
        self.assertEqual(client_verdict_of(attempt('Wrong'), False), 'Wrong')
        self.assertEqual(client_verdict_of(attempt('Partial', RARE_FOUND_COMMENT), True), 'Wrong')
        self.assertEqual(client_verdict_of(attempt('Partial', EXTRA_FOUND_COMMENT), True), 'Wrong')
        self.assertEqual(client_verdict_of(attempt('Wrong', 'Слово уже открыто'), True), 'Wrong')


@override_settings(OFFLINE_PLAY_ENABLED=True)
class InstantSaladPageTests(_ClientEventFixture):
    @classmethod
    def setUpTestData(cls):
        super().setUpTestData()
        salad = parse_word_salad_csv(SAMPLE_CSV)[1]
        cls.words = [normalize_word(word) for word in salad['words']]
        cls.grid = salad['grid']
        checker, _ = CheckerType.objects.get_or_create(pk='word_salad')
        cls.salad = Task.objects.create(
            task_group=cls.tg, number='3', task_type='word_salad', checker=checker, points=1,
            checker_data=serialize_task_data(cls.grid, cls.words), answer='',
        )

    def setUp(self):
        super().setUp()
        caches['offline_play'].clear()

    def _post_path(self, word, verdict='Ok', event_id=None):
        path = find_paths(self.grid, word, limit=1)[0]
        data = {
            'game_id': self.game.id, 'anon_key': self.anon_key, 'path': json.dumps(path),
            'correct_only': '1', 'client_verdict': verdict, 'client_event_id': str(event_id or uuid.uuid4()),
        }
        return self.client.post(
            '/send_attempt/{}/'.format(self.salad.id), data, HTTP_X_REQUESTED_WITH='XMLHttpRequest',
        ).json()

    def _card(self, word):
        # The card the server sends back with a credited word.
        return self._post_path(word)['update_task_html_new'][str(self.salad.id)]

    def test_card_marks_instant_verdict_only_with_a_rule(self):
        self.assertNotIn('data-instant-verdict', self._card(self.words[0]))
        OfflinePlayRule.objects.create(task_type='word_salad', instant_verdict=True)
        self.assertIn('data-instant-verdict="1"', self._card(self.words[1]))

    @override_settings(OFFLINE_PLAY_ENABLED=False)
    def test_kill_switch_hides_instant_verdict(self):
        OfflinePlayRule.objects.create(task_type='word_salad', instant_verdict=True)
        self.assertNotIn('data-instant-verdict', self._card(self.words[0]))

    @patch('games.ops.telegram.bot.notify.notify_admin_offline_play')
    def test_agreeing_verdict_is_quiet_and_a_resent_word_counts_once(self, notify):
        event_id = uuid.uuid4()
        first = self._post_path(self.words[0], event_id=event_id)
        self.assertTrue(first['word_salad_correct'])
        again = self._post_path(self.words[0], event_id=event_id)
        self.assertTrue(again['client_event_replayed'])
        self.assertTrue(again['word_salad_correct'])
        notify.assert_not_called()

    @patch('games.ops.telegram.bot.notify.notify_admin_offline_play')
    def test_page_calling_a_non_answer_correct_is_reported(self, notify):
        data = {
            'game_id': self.game.id, 'anon_key': self.anon_key, 'path': json.dumps([0, 1]),
            'correct_only': '1', 'client_verdict': 'Ok', 'client_event_id': str(uuid.uuid4()),
        }
        with self.assertLogs('games.offline', 'WARNING') as logs:
            response = self.client.post(
                '/send_attempt/{}/'.format(self.salad.id), data, HTTP_X_REQUESTED_WITH='XMLHttpRequest',
            ).json()
        self.assertFalse(response.get('word_salad_correct'))
        self.assertIn('server=Wrong', ' '.join(logs.output))
        self.assertEqual(notify.call_args.kwargs['kind'], 'verdict_divergence')

    def test_page_claiming_a_repeated_path_is_reported(self):
        self._post_path(self.words[0])
        with self.assertLogs('games.offline', 'WARNING') as logs:
            response = self._post_path(self.words[0])
        self.assertEqual(response['status'], 'duplicate')
        self.assertIn('server=Duplicate', ' '.join(logs.output))
