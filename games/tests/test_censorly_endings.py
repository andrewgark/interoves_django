class GrammaticalEndingTests(SimpleTestCase):
    def test_golden_corpus_is_large_enough(self):
        self.assertGreaterEqual(len(GOLDEN), 150)
        surfaces = [normalize_surface(word) for word, _stem, _ending in GOLDEN]
        self.assertEqual(len(surfaces), len(set(surfaces)))

    def test_golden_endings(self):
        for word, stem, ending in GOLDEN:
            with self.subTest(word=word):
                self.assertEqual(split_stem_ending(word), (stem, ending))

    def test_golden_invariants(self):
        for word, stem, ending in GOLDEN:
            plain = normalize_surface(word)
            with self.subTest(word=word):
                self.assertEqual(stem + ending, plain)
                self.assertGreater(len(stem), 0)
                if ending:
                    self.assertTrue(plain.endswith(ending))
                    self.assertGreaterEqual(len(stem), 2)

    def test_short_stem_endings_are_shown(self):
        for word, stem, ending in SHORT_STEM:
            plain = normalize_surface(word)
            with self.subTest(word=word):
                self.assertEqual(grammatical_split(plain), (stem, ending))
                self.assertEqual(stem + ending, plain)
                self.assertGreaterEqual(len(stem), 2)
                self.assertEqual(split_stem_ending(word), (stem, ending))

    def test_edges_do_not_raise(self):
        cases = {
            '': ('', ''),
            'а': ('а', ''),
            'я': ('я', ''),
            'ъ': ('ъ', ''),
            'Санкт-Петербург': ('санкт-петербург', ''),
            'какой-то': ('какой-то', ''),
            '123': ('123', ''),
            '12а': ('12а', ''),
            'mc2': ('mc2', ''),
            'Paris': ('paris', ''),
            'кот!': ('кот!', ''),
            '   ': ('', ''),
            'фывапролдж': ('фывапролдж', ''),
            'МОРЕ': ('мор', 'е'),
            'ФРАНЦИИ': ('франци', 'и'),
        }
        for word, expected in cases.items():
            with self.subTest(word=word):
                self.assertEqual(split_stem_ending(word), expected)

    def test_arbitrary_strings_do_not_raise(self):
        rng = random.Random(0)
        alphabet = 'абвгдеёжзийклмнопрстуфхцчшщъыьэюяАБВ- 123!?.,ё'
        samples = ['', 'а', 'Ё', 'ь', 'ъ', '\n', ' ', '—', '①', '東京']
        for _ in range(300):
            samples.append(''.join(rng.choice(alphabet) for _ in range(rng.randint(0, 24))))
        for sample in samples:
            with self.subTest(sample=sample):
                stem, ending = split_stem_ending(sample)
                plain = normalize_surface(sample)
                self.assertEqual(stem + ending, plain)
                if ending:
                    self.assertTrue(plain.endswith(ending))
                    self.assertGreaterEqual(len(stem), 2)


