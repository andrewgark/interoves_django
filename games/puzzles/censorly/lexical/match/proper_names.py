def _expand_variant_groups(groups: tuple[tuple[str, ...], ...]) -> tuple[tuple[str, str], ...]:
    """Return direct undirected edges for each curated synonym group."""
    return tuple(
        (left, right)
        for group in groups
        for index, left in enumerate(group)
        for right in group[index + 1:]
    )


